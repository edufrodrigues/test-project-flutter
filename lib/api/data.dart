Booking _seedBooking(
  List<Experience> experiences,
  String experienceId,
  String code,
  int dayOffset,
  int guests,
  BookingStatus status,
) {
  final experience = experiences.firstWhere((item) => item.id == experienceId);
  final today = RotaDate.today();
  return Booking(
    id: code,
    experienceId: experienceId,
    experienceTitle: experience.title,
    location: experience.location,
    art: experience.art,
    date: RotaDate.addDays(today, dayOffset),
    guests: guests,
    total: experience.price * guests,
    name: seedProfile.name,
    email: seedProfile.email,
    phone: seedProfile.phone,
    notes: '',
    status: status,
    createdAt: RotaDate.addDays(today, dayOffset - 20),
  );
}

