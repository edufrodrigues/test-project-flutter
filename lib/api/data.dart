/// Gera datas futuras a partir de hoje, para os dados nunca ficarem vencidos.
List<DateTime> _nextDates(List<int> offsets) {
  final base = RotaDate.today();
  return [for (final offset in offsets) RotaDate.addDays(base, offset)];
}

